export const ROBLOX_BRICK_COLORS: BrickColorEntry[] = RAW_BRICKCOLOR_ROWS.map(([name, code, rgb, hex]) => {
  const [r, g, b] = rgb.split(',').map((n) => parseInt(n, 10));
  return { name, code, r, g, b, rgb, hex };
});

export function findNearestBrickColor(r: number, g: number, b: number): {
  match: BrickColorEntry;
  distance: number;
} {
  let best = ROBLOX_BRICK_COLORS[0];
  let bestDistSq = Infinity;

  for (const bc of ROBLOX_BRICK_COLORS) {
    const dr = r - bc.r;
    const dg = g - bc.g;
    const db = b - bc.b;
    const distSq = dr * dr + dg * dg + db * db;
    if (distSq < bestDistSq) {
      bestDistSq = distSq;
      best = bc;
    }
  }

  return {
    match: best,
    distance: Math.sqrt(bestDistSq)
  };
}
